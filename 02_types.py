# Now we are going to learn about data types.
# Python has a lot of data types:
# - Numeric: int, float, complex
# - Text & Boolean: str, bool
# - Collections: list, tuple, range, dict, set, frozenset
# - Null: NoneType

# Don't worry, you don't need to memorize all of these right now
# Luckily, Python has a handy built-in function called type() to check what kind of data anything is:

# These are the most basic data types:

# str: Any text inside quotes
print(type("example"))

# int: Whole numbers without decimals
print(type(900))

# float: Numbers with decimal points (even ones ending in .0)
print(type(2.1))
print(type(1.0))

# complex: Like in math, numbers with a real part (1, 2, 3) and an imaginary part (j)
print(type(1 + 2j))

# bool: Represents True or False, often the result of logical comparisons
print(type(True))
print(type(5 > 3))

# NoneType: Represents the absence of a value (using the word None)
print(type(None))

