# If you want to separate multiple phrases with a specific character,
# you can use the sep="-" parameter.
# Here I use commas (,) to pass multiple words, separated by a "-":
print("hi", "if", "you", "watch", "this", sep="-")

# You can use the end="" parameter to choose how the output ends,
# by default it is a line break with end="\n",
# such as adding a question mark with end="?"
print("this is a question", end="?")

